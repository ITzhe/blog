# 画布：bytearray，RGB
buf = bytearray(W * H * 3)


def put(x, y, color, alpha=1.0):
    if not (0 <= x < W and 0 <= y < H):
        return
    o = (y * W + x) * 3
    if alpha >= 1.0:
        buf[o:o + 3] = bytes(color)
    else:
        for i in range(3):
            buf[o + i] = int(round(buf[o + i] + (color[i] - buf[o + i]) * alpha))


def lerp(a, b, t):
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(3))


# ---------- 背景 ----------
for y in range(H):
    t = y / (H - 1)
    c = lerp(BG_TOP, BG_BOT, t)
    for x in range(W):
        o = (y * W + x) * 3
        buf[o:o + 3] = bytes(c)

# 网格
for y in range(H):
    if y % 72 == 0:
        for x in range(W):
            put(x, y, GRID, 0.5)
for x in range(W):
    if x % 72 == 0:
        for y in range(H):
            put(x, y, GRID, 0.5)

# 右下角柔和光晕（用同心圆近似，无渐变 API）
cx, cy = int(W * 0.82), int(H * 0.78)
for r in range(340, 0, -1):
    a = 0.055 * (1 - r / 340.0)
    for deg in range(0, 360, 3):
        import math
        x = int(cx + r * math.cos(math.radians(deg)))
        y = int(cy + r * math.sin(math.radians(deg)))
        if 0 <= x < W and 0 <= y < H:
            put(x, y, ACCENT, a)

# 左侧强调竖条
for x in range(90, 96):
    for y in range(150, 480):
        put(x, y, ACCENT)


def draw_text(s, x0, y0, scale, color):
    """点阵字放大绘制。返回结束 x。"""
    x = x0
    for ch in s.upper():
        glyph = FONT.get(ch, FONT[" "])
        for gy, rowstr in enumerate(glyph):
            for gx, bit in enumerate(rowstr):
                if bit == "1":
                    for dy in range(scale):
                        for dx in range(scale):
                            put(x + gx * scale + dx,
                                y0 + gy * scale + dy, color)
        x += (5 + 1) * scale   # 字宽 5 + 字距 1
    return x


# 站名
draw_text("CAIZHE.ORG", 140, 190, 11, WHITE)

# 副标题
draw_text("LINUX - KUBERNETES - CLOUD NATIVE", 143, 300, 4, ACCENT)

# 一行说明
