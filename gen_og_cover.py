# 底部一行装饰点
for i in range(28):
    put(143 + i * 14, 430, ACCENT, 0.6 - i * 0.012)
    put(143 + i * 14, 431, ACCENT, 0.6 - i * 0.012)

# ---------- 编码 PNG ----------
rows = []
for y in range(H):
    o = y * W * 3
    rows.append(b"\x00" + bytes(buf[o:o + W * 3]))
raw = b"".join(rows)


def chunk(typ, data):
    c = struct.pack(">I", len(data)) + typ + data
    return c + struct.pack(">I", zlib.crc32(typ + data) & 0xFFFFFFFF)


png = b"\x89PNG\r\n\x1a\n"
png += chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0))
png += chunk(b"IDAT", zlib.compress(raw, 9))
png += chunk(b"IEND", b"")

with open("dist/og-cover.png", "wb") as f:
    f.write(png)

print("生成 dist/og-cover.png  %dx%d  %.1f KB" % (W, H, len(png) / 1024))
